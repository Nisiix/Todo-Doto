/**
 * Cartella del progetto sul PC di chi apre lo Stack.
 *
 * Il percorso salvato nel progetto è condiviso nel workspace, ma la stessa
 * cartella può avere un percorso diverso su ogni PC (es. U:\… su uno, una
 * condivisione di rete su un altro). Chi non la trova la cerca: la cartella
 * scelta si ricorda per questo PC (o, se l'amministratore lo vuole, diventa
 * quella del progetto per tutti). È valida solo se esiste, contiene un
 * progetto riconoscibile e si chiama come il progetto nell'applicazione.
 */
import { getFs } from './fs'
import { checkFolder } from './fsErrors'
import { inspectFolder } from './projectScan'

export type FolderProblem =
  /** Nessuna cartella indicata. */
  | 'empty'
  /** Non raggiungibile o non leggibile (rete, permessi…): vedi `detail`. */
  | 'unreachable'
  /** La cartella non esiste. */
  | 'missing'
  /** C'è, ma non contiene un progetto riconoscibile. */
  | 'not-project'
  /** Contiene un progetto, ma il nome della cartella non è quello del progetto. */
  | 'name'

export interface FolderCheck {
  ok: boolean
  path: string
  problem: FolderProblem | null
  /** Spiegazione dell'errore di rete/permessi (per 'unreachable'). */
  detail: string
}

/** Ultima parte del percorso (il nome della cartella). */
export const folderName = (path: string) => path.trim().split(/[\\/]+/).filter(Boolean).pop() ?? ''

/** Il nome della cartella corrisponde al nome del progetto (senza badare a maiuscole e spazi ai lati)? */
export const sameName = (path: string, projectName: string) => folderName(path).trim().toLowerCase() === projectName.trim().toLowerCase()

/** Verifica che `path` sia la cartella del progetto `projectName`. */
export async function validateProjectFolder(path: string, projectName: string): Promise<FolderCheck> {
  const p = path.trim()
  const no = (problem: FolderProblem, detail = ''): FolderCheck => ({ ok: false, path: p, problem, detail })
  if (!p) return no('empty')
  const fs = await getFs()
  const problem = await checkFolder(fs, p)
  if (problem) return no('unreachable', problem)
  const { kind } = await inspectFolder(p)
  if (kind === 'missing') return no('missing')
  // Progetto appena creato con l'app: c'è solo il README generato, il codice arriverà
  if (kind !== 'project' && !(await generatedByApp(p))) return no('not-project')
  if (!sameName(p, projectName)) return no('name')
  return { ok: true, path: p, problem: null, detail: '' }
}

/** La cartella è stata creata dall'app (README "Generato da Todo Doto", anche col nome precedente)? */
async function generatedByApp(path: string): Promise<boolean> {
  const fs = await getFs()
  const readme = await fs.readText(await fs.join(path, 'README.md')).catch(() => '')
  return /(Generato da|Generated by) (Todo Doto|Project Goal Manager)/.test(readme)
}

// --- percorso trovato su questo PC -------------------------------------------------------

const key = (workspaceId: string, projectId: string) => `pgm:projectPath:${workspaceId}:${projectId}`

/** Cartella del progetto ricordata per questo PC ('' se nessuna). */
export function getLocalProjectPath(workspaceId: string, projectId: string): string {
  try {
    return localStorage.getItem(key(workspaceId, projectId)) ?? ''
  } catch {
    return ''
  }
}

export function setLocalProjectPath(workspaceId: string, projectId: string, path: string | null) {
  try {
    if (path) localStorage.setItem(key(workspaceId, projectId), path)
    else localStorage.removeItem(key(workspaceId, projectId))
  } catch {
    /* solo comodità locale */
  }
}
